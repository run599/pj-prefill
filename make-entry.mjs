// scripts/make-entry.mjs —— 生成一个新入口文件，用来绕开 DSH 的 ESM URL 缓存。
//
// 为什么需要它：DSH 宿主按 **模块 URL** 缓存已加载的 ESM。改了 plugin.mjs 或 lib/*.mjs
// 的内容，运行中的宿主仍跑旧代码。已实测的两种解法是「换文件名/新 URL」或「重启 DSH」。
// 本脚本走前者：把 lib/ 的 import 加上 `?v=<tag>` 查询串（file:// URL 带 query 是合法
// 模块标识），从而让所有 lib 模块都变成新 URL、被重新加载。
//
// 用法：
//   node scripts/make-entry.mjs                    # 默认 1.1.0 + 时间戳 tag
//   node scripts/make-entry.mjs 1.2.0 v3           # 指定版本与 tag
// 生成后把 preset 里的挂载行指向新的 plugin.<tag>.mjs（insert 行热加载，不用重启）。
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = dirname(HERE)

const ver = process.argv[2] || '1.1.0'
const tag = process.argv[3] || String(Date.now())

const src = readFileSync(join(ROOT, 'plugin.mjs'), 'utf8')

let out = src.replace(/(from '\.\/lib\/[a-z]+\.mjs)'/g, `$1?v=${tag}'`)
if (!/\?v=/.test(out)) {
  console.error('FAIL 没能在 plugin.mjs 里找到 ./lib/*.mjs 的 import —— 入口结构可能变了')
  process.exit(1)
}
out = out.replace(/export const VERSION = '[^']+'/, `export const VERSION = '${ver}'`)
out = out.replace(/^\/\/ pj-prefill v[\d.]+/m, `// pj-prefill v${ver}`)
out = `// AUTO-GENERATED by scripts/make-entry.mjs —— 不要直接编辑；改 plugin.mjs 后重新生成。\n`
  + `// cacheTag=${tag}  (lib imports carry ?v=${tag} to defeat the host's ESM URL cache)\n`
  + out

const dest = join(ROOT, `plugin.${tag}.mjs`)
writeFileSync(dest, out, 'utf8')

const n = (out.match(/\?v=/g) || []).length
console.log(`wrote ${dest}`)
console.log(`  version=${ver}  cacheTag=${tag}  lib-imports-rewritten=${n}`)
console.log(`  下一步：把 preset 的挂载行指向 file:///${dest.replace(/\\/g, '/')}`)
